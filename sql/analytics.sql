-- =========================================
-- 1. SALES DATA
-- =========================================

CREATE OR REPLACE TABLE ECOMMERCE_DB.ANALYTICS.SALES_DATA AS

SELECT
    o.ORDER_ID,
    o.CUSTOMER_ID,

    c.CUSTOMER_UNIQUE_ID,
    c.CUSTOMER_CITY,
    c.CUSTOMER_STATE,

    o.ORDER_STATUS,
    o.ORDER_PURCHASE_TIMESTAMP,
    o.ORDER_APPROVED_AT,
    o.ORDER_DELIVERED_CARRIER_DATE,
    o.ORDER_DELIVERED_CUSTOMER_DATE,
    o.ORDER_ESTIMATED_DELIVERY_DATE,

    oi.ORDER_ITEM_ID,
    oi.PRODUCT_ID,
    oi.SELLER_ID,
    oi.SHIPPING_LIMIT_DATE,
    oi.PRICE,
    oi.FREIGHT_VALUE,

    p.PRODUCT_CATEGORY_NAME,
    p.PRODUCT_NAME_LENGTH,
    p.PRODUCT_DESCRIPTION_LENGTH,
    p.PRODUCT_PHOTOS_QTY,
    p.PRODUCT_WEIGHT_G,
    p.PRODUCT_LENGTH_CM,
    p.PRODUCT_HEIGHT_CM,
    p.PRODUCT_WIDTH_CM,

    oi.PRICE + oi.FREIGHT_VALUE AS TOTAL_ITEM_VALUE,

    CAST(o.ORDER_PURCHASE_TIMESTAMP AS DATE) AS PURCHASE_DATE,

    YEAR(o.ORDER_PURCHASE_TIMESTAMP) AS PURCHASE_YEAR,

    MONTH(o.ORDER_PURCHASE_TIMESTAMP) AS PURCHASE_MONTH,

    TO_CHAR(
        o.ORDER_PURCHASE_TIMESTAMP,
        'YYYY-MM'
    ) AS PURCHASE_YEAR_MONTH

FROM ECOMMERCE_DB.STAGING.ORDERS o

LEFT JOIN ECOMMERCE_DB.STAGING.CUSTOMERS c
    ON o.CUSTOMER_ID = c.CUSTOMER_ID

LEFT JOIN ECOMMERCE_DB.STAGING.ORDER_ITEMS oi
    ON o.ORDER_ID = oi.ORDER_ID

LEFT JOIN ECOMMERCE_DB.STAGING.PRODUCTS p
    ON oi.PRODUCT_ID = p.PRODUCT_ID;


-- =========================================
-- 2. ORDER SUMMARY
-- =========================================

CREATE OR REPLACE TABLE ECOMMERCE_DB.ANALYTICS.ORDER_SUMMARY AS

SELECT
    ORDER_ID,

    SUM(TOTAL_ITEM_VALUE) AS TOTAL_ORDER_VALUE,

    SUM(PRICE) AS TOTAL_PRODUCT_VALUE,

    SUM(FREIGHT_VALUE) AS TOTAL_FREIGHT_VALUE,

    COUNT(ORDER_ITEM_ID) AS TOTAL_ITEMS

FROM ECOMMERCE_DB.ANALYTICS.SALES_DATA

GROUP BY ORDER_ID;


-- =========================================
-- 3. CUSTOMER SUMMARY
-- =========================================

CREATE OR REPLACE TABLE ECOMMERCE_DB.ANALYTICS.CUSTOMER_SUMMARY AS

SELECT
    CUSTOMER_UNIQUE_ID,

    CUSTOMER_CITY,

    CUSTOMER_STATE,

    COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS,

    COUNT(ORDER_ITEM_ID) AS TOTAL_ITEMS,

    SUM(TOTAL_ITEM_VALUE) AS TOTAL_SPENT,

    SUM(FREIGHT_VALUE) AS TOTAL_FREIGHT

FROM ECOMMERCE_DB.ANALYTICS.SALES_DATA

GROUP BY
    CUSTOMER_UNIQUE_ID,
    CUSTOMER_CITY,
    CUSTOMER_STATE;


-- =========================================
-- 4. CATEGORY SUMMARY
-- =========================================

CREATE OR REPLACE TABLE ECOMMERCE_DB.ANALYTICS.CATEGORY_SUMMARY AS

SELECT
    PRODUCT_CATEGORY_NAME,

    COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS,

    COUNT(ORDER_ITEM_ID) AS TOTAL_ITEMS,

    SUM(PRICE) AS TOTAL_SALES,

    SUM(FREIGHT_VALUE) AS TOTAL_FREIGHT,

    SUM(TOTAL_ITEM_VALUE) AS TOTAL_REVENUE

FROM ECOMMERCE_DB.ANALYTICS.SALES_DATA

WHERE PRODUCT_CATEGORY_NAME IS NOT NULL

GROUP BY PRODUCT_CATEGORY_NAME;


-- =========================================
-- ANALYTICS ROW COUNT VERIFICATION
-- =========================================

SELECT COUNT(*) AS SALES_DATA_ROWS
FROM ECOMMERCE_DB.ANALYTICS.SALES_DATA;

SELECT COUNT(*) AS ORDER_SUMMARY_ROWS
FROM ECOMMERCE_DB.ANALYTICS.ORDER_SUMMARY;

SELECT COUNT(*) AS CUSTOMER_SUMMARY_ROWS
FROM ECOMMERCE_DB.ANALYTICS.CUSTOMER_SUMMARY;

SELECT COUNT(*) AS CATEGORY_SUMMARY_ROWS
FROM ECOMMERCE_DB.ANALYTICS.CATEGORY_SUMMARY;