-- =========================================
-- STAGING LAYER
-- E-Commerce Data Engineering Project
-- =========================================


-- =========================================
-- 1. CUSTOMERS
-- =========================================

CREATE OR REPLACE TABLE ECOMMERCE_DB.STAGING.CUSTOMERS AS

SELECT
    TRIM(CUSTOMER_ID) AS CUSTOMER_ID,
    TRIM(CUSTOMER_UNIQUE_ID) AS CUSTOMER_UNIQUE_ID,
    TRIM(CUSTOMER_ZIP_CODE_PREFIX) AS CUSTOMER_ZIP_CODE_PREFIX,
    LOWER(TRIM(CUSTOMER_CITY)) AS CUSTOMER_CITY,
    UPPER(TRIM(CUSTOMER_STATE)) AS CUSTOMER_STATE

FROM ECOMMERCE_DB.RAW.CUSTOMERS;


-- =========================================
-- 2. ORDERS
-- =========================================

CREATE OR REPLACE TABLE ECOMMERCE_DB.STAGING.ORDERS AS

SELECT
    TRIM(ORDER_ID) AS ORDER_ID,
    TRIM(CUSTOMER_ID) AS CUSTOMER_ID,
    LOWER(TRIM(ORDER_STATUS)) AS ORDER_STATUS,

    ORDER_PURCHASE_TIMESTAMP,
    ORDER_APPROVED_AT,
    ORDER_DELIVERED_CARRIER_DATE,
    ORDER_DELIVERED_CUSTOMER_DATE,
    ORDER_ESTIMATED_DELIVERY_DATE

FROM ECOMMERCE_DB.RAW.ORDERS;


-- =========================================
-- 3. ORDER ITEMS
-- =========================================

CREATE OR REPLACE TABLE ECOMMERCE_DB.STAGING.ORDER_ITEMS AS

SELECT
    TRIM(ORDER_ID) AS ORDER_ID,
    ORDER_ITEM_ID,
    TRIM(PRODUCT_ID) AS PRODUCT_ID,
    TRIM(SELLER_ID) AS SELLER_ID,
    SHIPPING_LIMIT_DATE,
    PRICE,
    FREIGHT_VALUE

FROM ECOMMERCE_DB.RAW.ORDER_ITEMS;


-- =========================================
-- 4. PRODUCTS
-- =========================================

CREATE OR REPLACE TABLE ECOMMERCE_DB.STAGING.PRODUCTS AS

SELECT
    TRIM(PRODUCT_ID) AS PRODUCT_ID,
    LOWER(TRIM(PRODUCT_CATEGORY_NAME)) AS PRODUCT_CATEGORY_NAME,

    PRODUCT_NAME_LENGTH,
    PRODUCT_DESCRIPTION_LENGTH,
    PRODUCT_PHOTOS_QTY,
    PRODUCT_WEIGHT_G,
    PRODUCT_LENGTH_CM,
    PRODUCT_HEIGHT_CM,
    PRODUCT_WIDTH_CM

FROM ECOMMERCE_DB.RAW.PRODUCTS;


-- =========================================
-- VERIFY ROW COUNTS
-- =========================================

SELECT COUNT(*) AS CUSTOMER_ROWS
FROM ECOMMERCE_DB.STAGING.CUSTOMERS;

SELECT COUNT(*) AS ORDER_ROWS
FROM ECOMMERCE_DB.STAGING.ORDERS;

SELECT COUNT(*) AS ORDER_ITEM_ROWS
FROM ECOMMERCE_DB.STAGING.ORDER_ITEMS;

SELECT COUNT(*) AS PRODUCT_ROWS
FROM ECOMMERCE_DB.STAGING.PRODUCTS;