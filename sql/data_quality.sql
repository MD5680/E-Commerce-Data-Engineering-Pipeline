-- =========================================
-- DATA QUALITY CHECKS
-- E-Commerce Data Engineering Project
-- =========================================


-- =========================================
-- 1. SALES DATA CHECKS
-- =========================================

SELECT
    COUNT(*) AS TOTAL_ROWS,

    COUNT_IF(ORDER_ID IS NULL) AS MISSING_ORDER_IDS,

    COUNT_IF(PRODUCT_ID IS NULL) AS MISSING_PRODUCT_IDS,

    COUNT_IF(PRICE < 0) AS NEGATIVE_PRICES,

    COUNT_IF(FREIGHT_VALUE < 0) AS NEGATIVE_FREIGHT,

    COUNT_IF(TOTAL_ITEM_VALUE < 0) AS NEGATIVE_TOTAL_VALUES

FROM ECOMMERCE_DB.ANALYTICS.SALES_DATA;


-- =========================================
-- 2. ORDER SUMMARY CHECKS
-- =========================================

SELECT
    COUNT(*) AS TOTAL_ORDERS,

    COUNT_IF(ORDER_ID IS NULL) AS MISSING_ORDER_IDS,

    COUNT(DISTINCT ORDER_ID) AS UNIQUE_ORDERS,

    COUNT_IF(TOTAL_ORDER_VALUE < 0) AS NEGATIVE_ORDER_VALUES,

    COUNT_IF(TOTAL_ITEMS < 0) AS NEGATIVE_ITEM_COUNTS

FROM ECOMMERCE_DB.ANALYTICS.ORDER_SUMMARY;


-- =========================================
-- 3. CUSTOMER SUMMARY CHECKS
-- =========================================

SELECT
    COUNT(*) AS TOTAL_CUSTOMERS,

    COUNT_IF(CUSTOMER_UNIQUE_ID IS NULL) AS MISSING_CUSTOMER_IDS,

    COUNT_IF(CUSTOMER_CITY IS NULL) AS MISSING_CITIES,

    COUNT_IF(CUSTOMER_STATE IS NULL) AS MISSING_STATES,

    COUNT_IF(TOTAL_SPENT < 0) AS NEGATIVE_SPENDING,

    COUNT_IF(TOTAL_FREIGHT < 0) AS NEGATIVE_FREIGHT

FROM ECOMMERCE_DB.ANALYTICS.CUSTOMER_SUMMARY;


-- =========================================
-- 4. CATEGORY SUMMARY CHECKS
-- =========================================

SELECT
    COUNT(*) AS TOTAL_CATEGORIES,

    COUNT_IF(PRODUCT_CATEGORY_NAME IS NULL)
        AS MISSING_CATEGORIES,

    COUNT_IF(TOTAL_SALES < 0)
        AS NEGATIVE_SALES,

    COUNT_IF(TOTAL_REVENUE < 0)
        AS NEGATIVE_REVENUE,

    COUNT_IF(TOTAL_FREIGHT < 0)
        AS NEGATIVE_FREIGHT

FROM ECOMMERCE_DB.ANALYTICS.CATEGORY_SUMMARY;


-- =========================================
-- 5. BUSINESS TOTAL RECONCILIATION
-- =========================================

SELECT
    SUM(TOTAL_ORDER_VALUE) AS TOTAL_REVENUE,

    SUM(TOTAL_PRODUCT_VALUE) AS TOTAL_PRODUCT_SALES,

    SUM(TOTAL_FREIGHT_VALUE) AS TOTAL_FREIGHT,

    SUM(TOTAL_ITEMS) AS TOTAL_ITEMS

FROM ECOMMERCE_DB.ANALYTICS.ORDER_SUMMARY;


-- =========================================
-- 6. CATEGORY REVENUE RECONCILIATION
-- =========================================

SELECT
    SUM(TOTAL_SALES) AS CATEGORY_PRODUCT_SALES,

    SUM(TOTAL_FREIGHT) AS CATEGORY_FREIGHT,

    SUM(TOTAL_REVENUE) AS CATEGORY_REVENUE

FROM ECOMMERCE_DB.ANALYTICS.CATEGORY_SUMMARY;